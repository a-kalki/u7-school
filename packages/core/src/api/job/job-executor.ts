import type { Job } from './job';

/**
 * Порт исполнителя прогона задания.
 *
 * Точка расширения для будущего выноса тяжёлых job'ов
 * в отдельный процесс (воркер): реализация порта решает, ГДЕ
 * выполнить execute(). Контракт Job при этом не меняется.
 *
 * Текущая реализация — InProcJobExecutor (прогон в текущем процессе).
 * Предусловие для воркера — внешнее хранилище (in-memory JSON-репо
 * недоступны из другого процесса).
 */
export interface JobExecutor {
  /** Выполняет один прогон задания. Ошибки прогона — на планировщике. */
  execute(job: Job): Promise<void>;
}
