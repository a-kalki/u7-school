import * as v from 'valibot';

/**
 * Виды уведомлений — единый словарь механизма уведомлений.
 *
 * Канало-агностичная семантика «важности реплики», а не презентация:
 * транспорт (Telegram/web) сам отображает вид в оформление
 * (заголовок, иконка). Живёт в domain-слое фреймворка, потому что
 * путешествует внутри доменных событий (например, user.notified) и
 * легален для импорта всем слоям — от агрегатов до UI.
 *
 * - `notify` — нейтральное уведомление (по умолчанию);
 * - `info` — информационная заметка;
 * - `warn` — предупреждение, требующее внимания.
 */
export const NOTIFY_KINDS = ['notify', 'info', 'warn'] as const;

/** Вид уведомления */
export type NotifyKind = (typeof NOTIFY_KINDS)[number];

/** Схема валидации вида уведомления */
export const NotifyKindSchema = v.picklist(NOTIFY_KINDS);
