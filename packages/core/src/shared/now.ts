/**
 * Текущий момент времени — единственная точка чтения системных часов
 * в продакшн-коде. Любой код, которому нужно «сейчас», обязан брать его
 * отсюда: это позволяет тестам замораживать время (`spyOn(Shared, 'now')`)
 * без правки прод-кода.
 */
export function now(): Date {
  return new Date();
}
