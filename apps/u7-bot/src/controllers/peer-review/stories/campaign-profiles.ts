import { type MdText, md, mdJoin } from '@u7-scl/core/shared';
import type {
  AuthorRole,
  MyCampaignCard,
  StudentOutcome,
} from '@u7-scl/peer-review/domain';

/**
 * Профиль кампании — видонезависимое ядро стори кампании (навигация,
 * ввод, сохранение, справка) берёт здесь ТОЛЬКО тексты и подписи,
 * зависящие от вида кампании. Новый вид (мероприятие, код-ревью, …) —
 * новый файл-профиль + строка в реестре внизу; стори и хаб не меняются.
 *
 * Парные тексты «роль-судьба» — сердце профиля судьбы потока
 * (ui-spec 2026-09-22): тон нейтральный, passed/not_passed не различаются.
 */
export interface CampaignProfile {
  /** Заголовок S03 (жирный) — «О чём экран»: вид + название скоупа. */
  listHeader(title: string): MdText;
  /** Заголовок S05/S04 (жирный) — шапка-ориентир экрана ввода. */
  askHeader(title: string): MdText;
  /** Подпись роли адресата в кнопке S03 — взгляд автора. */
  recipientLabel(role: 'mentor' | 'student', myRole: AuthorRole): string;
  /** Заголовок мини-карточки хаба S02 — «Поток «{title}»». */
  hubCardTitle(title: string): string;
  /** Кнопка хаба, я — субъект: «1. Поток «{title}»». */
  hubSubjectBtn(no: number, title: string): string;
  /** Кнопка хаба, я — ментор: «2. Отзыв об {Имя}» (фолбэк — в падеже). */
  hubMentorBtn(no: number, subjectName: string | undefined): string;
  /** Мини-карточка хаба — по паре «роль-судьба». */
  hubCardText(card: MyCampaignCard, subjectName: string | undefined): string;
  /** Вводный абзац S03 — по паре «роль-судьба»: кому и зачем полезен отзыв. */
  listIntro(
    myRole: AuthorRole,
    subjectOutcome: StudentOutcome,
    subjectName: string | undefined,
  ): MdText[];
  /** Подсказка S05 — по направлению «кто о ком» (+ судьба для «о менторе»). */
  askPrompt(input: {
    myRole: AuthorRole;
    recipientRole: 'mentor' | 'student';
    name: string;
    subjectOutcome: StudentOutcome;
  }): MdText;
}

/** Судьба студента потока — единственный вид кампаний сегодня. */
export const STREAM_FATE_PROFILE: CampaignProfile = {
  listHeader: (title) => md`✍️ *Отзывы — поток «${title}»*`,
  askHeader: (title) => md`✍️ *Отзыв — поток «${title}»*`,
  recipientLabel: (role, myRole) => {
    if (role === 'mentor') return 'Ментор';
    return myRole === 'subject' ? 'Одногруппник' : 'Студент';
  },
  hubCardTitle: (title) => `Поток «${title}»`,
  hubSubjectBtn: (no, title) => `${no}. Поток «${title}»`,
  hubMentorBtn: (no, subjectName) =>
    `${no}. Отзыв об ${subjectName ?? 'студенте'}`,
  hubCardText: (card, subjectName) => {
    const name = subjectName ?? 'студент';
    if (card.myRole === 'mentor') {
      return card.subjectOutcome === 'completed_passed' ||
        card.subjectOutcome === 'completed_not_passed'
        ? `Ты был ментором этого потока. Твой подопечный ${name} завершил обучение — выдай ему отзыв: как проявлялся, что удалось, что стоит подтянуть.`
        : `Ты был ментором этого потока. Твой подопечный ${name} покинул обучение — поделись наблюдениями: что можно было сделать иначе.`;
    }
    switch (card.subjectOutcome) {
      case 'dropped':
        return 'Ты покинул обучение. Оставь отзыв ментору — что помогало, что мешало: школа учтёт это, а желающие пройти обучение смогут лучше понимать, что их ожидает.';
      case 'never_started':
        return 'Ты записался, но не начал обучение. Расскажи, что остановило твоё обучение: это будет полезно школе, ментору и тем, кто хочет начать обучение в нашей школе.';
      // «завершил и прошёл» / «завершил и не прошёл» — текст один
      default:
        return 'Ты завершил обучение. Поделись впечатлениями об учёбе — это помогает участникам расти, а также станет частью цифрового профиля студента и ментора.';
    }
  },
  listIntro: (myRole, subjectOutcome, subjectName) => {
    const name = subjectName ?? 'студент';
    if (myRole === 'mentor') {
      if (
        subjectOutcome === 'completed_passed' ||
        subjectOutcome === 'completed_not_passed'
      ) {
        return [
          md`Ты был ментором этого потока\\. Выдай отзыв о подопечном — ${name}: как он проявлялся в учёбе, что удалось, что стоит подтянуть\\.`,
          md``,
          md`Отзыв станет частью его цифрового профиля: следующие менторы и работодатели увидят, с чем он справляется\\.`,
        ];
      }
      return [
        md`Ты был ментором этого потока\\. Подопечный ${name} покинул обучение — поделись наблюдениями: что удавалось, что можно было сделать иначе\\.`,
        md``,
        md`Школе это поможет лучше поддерживать студентов, а ${name} — вернуться, когда будет готов\\.`,
      ];
    }
    switch (subjectOutcome) {
      case 'dropped':
        return [
          md`Ты покинул обучение в этом потоке\\. Ментору и школе будет полезно понять, что помогало, а что мешало\\. Честный отзыв — лучший вклад в школу: тем, кто только выбирает обучение, он подскажет, чего от него ожидать\\.`,
        ];
      case 'never_started':
        return [
          md`Ты записался на поток, но не начал обучение\\. Расскажи, что тебя остановило: школа это учтёт и уберёт барьеры, а тем, кто раздумывает начинать, твой отзыв поможет принять решение с открытыми глазами\\.`,
        ];
      // «завершил и прошёл» / «завершил и не прошёл» — текст один
      default:
        return [
          md`Ты завершил обучение в этом потоке\\. Расскажи о совместной учёбе: что запомнилось, что было полезно, что можно улучшить\\. Пиши кому хочешь и сколько хочешь\\.`,
          md``,
          md`Отзыв одногруппникам поможет увидеть, что у них хорошо получается, а что стоит подтянуть\\. Если кто\\-то помог, с кем\\-то было приятно сотрудничать — или наоборот, опыт был неприятным, — всё это полезно и им, и тем, кто будет с ними работать\\.`,
          md``,
          md`Отзыв ментору поможет понять, что у него получается, а что нет\\. А потенциальным студентам — понять, подходит ли им этот ментор\\.`,
        ];
    }
  },
  askPrompt: ({ myRole, recipientRole, name, subjectOutcome }) => {
    const lead = md`Предлагаем разделить отзыв на две части\\.`;
    if (recipientRole === 'student') {
      if (myRole === 'mentor') {
        return mdJoin([
          lead,
          md``,
          md`Сначала — \`Отзыв для {Имя}:\` \\(вместо \\{Имя\\} — ${name}\\) как студент проявлялся в учёбе: сильные стороны, чего удалось достичь за поток\\.`,
          md``,
          md`Затем с новой строки — \`Рекомендация по развитию:\` что стоит подтянуть и в каком направлении расти\\.`,
        ]);
      }
      return mdJoin([
        lead,
        md``,
        md`Сначала — \`Отзыв для {Имя}:\` \\(вместо \\{Имя\\} — ${name}\\) расскажи, как ${name} проявил\\(а\\) себя в учёбе — профессиональные, командные и личностные качества\\. Не обязательно перечислять всё — пиши то, что считаешь важным, и правду\\.`,
        md``,
        md`Затем с новой строки — \`Как с ним работать:\` короткую рекомендацию тем, кто будет учиться или работать рядом\\.`,
      ]);
    }
    switch (subjectOutcome) {
      case 'dropped':
        return mdJoin([
          lead,
          md``,
          md`Сначала — \`Отзыв для ментора:\` почему забросил\\(а\\) учёбу, что помогало, что мешало, какие пожелания школе и ментору\\.`,
          md``,
          md`Затем с новой строки — \`Следует ожидать от курса:\` твою рекомендацию тем, кто хочет выбрать это обучение\\.`,
        ]);
      case 'never_started':
        return mdJoin([
          lead,
          md``,
          md`Сначала — \`Что остановило:\` почему так и не начал\\(а\\) учёбу, что не совпало с ожиданиями\\.`,
          md``,
          md`Затем с новой строки — \`Моя рекомендация:\` что стоит знать школе и тем, кто выбирает обучение\\.`,
        ]);
      // «завершил и прошёл» / «завершил и не прошёл» — текст один
      // (и защита от рассинхрона формы)
      default:
        return mdJoin([
          lead,
          md``,
          md`Сначала — \`Отзыв для ментора:\` что помогало учиться, что мешало, чего не хватило\\.`,
          md``,
          md`Затем с новой строки — \`Моя рекомендация студентам:\` кому и почему подойдёт этот ментор\\.`,
        ]);
    }
  },
};

/**
 * Реестр профилей по виду кампании. Неизвестный вид — профиль судьбы
 * потока (UI деградирует текстами, а не падает; новые виды обязаны
 * регистрироваться до релиза).
 */
const PROFILES: Record<string, CampaignProfile> = {
  stream_fate: STREAM_FATE_PROFILE,
};

/** Профиль текстов по виду кампании (card.context / view.context). */
export function campaignProfileOf(context: string): CampaignProfile {
  return PROFILES[context] ?? STREAM_FATE_PROFILE;
}
